#!/usr/bin/env node
// Lifts the token blocks out of globals.css into a plain stylesheet the studio
// pages can load directly. globals.css is Tailwind v4 source (`@import
// "tailwindcss"`, `@theme inline`) so a browser cannot parse it — but the
// `:root` / `.dark` custom-property blocks inside it are ordinary CSS.
//
// This exists so the film cannot drift from the app the way the six superseded
// design specs drifted from each other (DESIGN-LANGUAGE.md, "Why this exists").
// Change a value in globals.css, re-render, the film follows.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, "../../../../src/app/globals.css");
const OUT = resolve(here, "tokens.generated.css");

/** Returns the body of the first `selector { ... }` block, brace-balanced. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`no ${selector} block in ${SOURCE}`);
  let depth = 0;
  for (let i = css.indexOf("{", start); i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) {
      return css.slice(css.indexOf("{", start) + 1, i);
    }
  }
  throw new Error(`unbalanced ${selector} block in ${SOURCE}`);
}

/** Custom-property declarations only — drops comments and normal properties. */
function customProperties(body) {
  return body
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split(";")
    .map((d) => d.trim())
    .filter((d) => d.startsWith("--"))
    .map((d) => `  ${d};`)
    .join("\n");
}

const css = readFileSync(SOURCE, "utf8");
const light = customProperties(block(css, ":root"));
const dark = customProperties(block(css, ".dark"));

writeFileSync(
  OUT,
  [
    "/* GENERATED by extract-tokens.mjs — do not edit.",
    " * Source of truth: src/app/globals.css. Re-run `node studio/extract-tokens.mjs`.",
    " */",
    ":root {",
    light,
    "}",
    "",
    ".dark {",
    dark,
    "}",
    "",
  ].join("\n"),
);

const count = (s) => s.split("\n").filter(Boolean).length;
console.log(`tokens.generated.css — :root ${count(light)} props, .dark ${count(dark)} props`);
