const splitId = (id) => {
  const [, area, n] = /^J-([A-Z]+)-(\d+)$/.exec(id);
  return { area, n: Number(n) };
};

function claims(stage, { area, n }) {
  return (stage.ids ?? []).some((spec) => {
    const [a, range] = spec.split(":");
    const [lo, hi = lo] = range.split("-").map(Number);
    return a === area && n >= lo && n <= hi;
  });
}

export function stageOf(id) {
  const parts = splitId(id);
  return (
    STAGES.find((s) => claims(s, parts)) ?? STAGES.find((s) => (s.areas ?? []).includes(parts.area)) ?? null
  );
}

/** GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens. */
const anchor = (label) => label.toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, "").replace(/\s/g, "-");

/** "JOBS 1, 3, 24–25 · MOB 1" from the rows a stage holds, in catalog order of areas. */
function idRanges(ids) {
  const byArea = new Map();
  for (const id of ids) {
    const { area, n } = splitId(id);
    if (!byArea.has(area)) byArea.set(area, []);
    byArea.get(area).push(n);
  }
  return [...byArea]
    .map(([area, ns]) => {
      ns.sort((a, b) => a - b);
      const runs = [];
      for (const n of ns) {
        const last = runs.at(-1);
        if (last && n === last[1] + 1) last[1] = n;
        else runs.push([n, n]);
      }
      const pad = (n) => String(n).padStart(2, "0");
      return `${area} ${runs.map(([a, b]) => (a === b ? pad(a) : `${pad(a)}–${pad(b)}`)).join(", ")}`;
    })
    .join(" · ");
}

export function buildTable(rows) {
  const unassigned = rows.filter((r) => !stageOf(r.id)).map((r) => r.id);
  const count = (rs) => ({
    rows: rs.length,
    covered: rs.filter((r) => r.status === "covered").length,
    uncovered: rs.filter((r) => r.status === "uncovered").length,
    knownBug: rs.filter((r) => r.status === "known-bug").length,
    bugNoted: rs.filter((r) => r.journey.includes("(known bug:")).length,
  });
  const lines = [
    "| Stage | Catalog rows | Rows | Covered | Uncovered | Known-bug | Bug noted |",
    "|-------|--------------|-----:|--------:|----------:|----------:|----------:|",
  ];
  for (const s of STAGES) {
    const mine = rows.filter((r) => stageOf(r.id) === s);
    const c = count(mine);
    lines.push(
      `| [${s.label}](#${anchor(s.label)}) | ${idRanges(mine.map((r) => r.id))} | ${c.rows} | ${c.covered} | ${c.uncovered} | ${c.knownBug} | ${c.bugNoted} |`,
    );
  }
  const t = count(rows);
  lines.push(`| **All stages** | | **${t.rows}** | **${t.covered}** | **${t.uncovered}** | **${t.knownBug}** | **${t.bugNoted}** |`);
  return { table: lines.join("\n"), unassigned };
}

function main() {
  const mode = process.argv[2] ?? "";
  const { table, unassigned } = buildTable(parseCatalog(readFileSync(CATALOG, "utf8")));
  if (unassigned.length) {
    console.error(`journey-map: no stage for ${unassigned.join(", ")} — add it to STAGES in scripts/journey-map-counts.mjs`);
    process.exit(1);
  }
  if (!mode) {
    console.log(table);
    return;
  }
  const map = readFileSync(MAP, "utf8");
  const i = map.indexOf(START);
  const j = map.indexOf(END);
  if (i < 0 || j < i) {
    console.error(`journey-map: MAP.md has no ${START} … ${END} block`);
    process.exit(1);
  }
  const next = `${map.slice(0, i + START.length)}\n${table}\n${map.slice(j)}`;
  if (mode === "--write") {
    writeFileSync(MAP, next);
    console.log("journey-map: stage table written to tests/journeys/MAP.md");
  } else if (mode === "--check") {
    if (next !== map) {
      console.error("journey-map: MAP.md's stage table is stale — run node scripts/journey-map-counts.mjs --write");
      process.exit(1);
    }
    console.log("journey-map: MAP.md's stage table is current");
  } else {
    console.error(`journey-map: unknown option ${mode}`);
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
