// tests/journeys/CATALOG.md through the parser the catalog lint uses, puts
// every row in one user stage, and prints the table (IDs and counts per stage).
//
//   node scripts/journey-map-counts.mjs           print the table
//   node scripts/journey-map-counts.mjs --write   replace the table in MAP.md
//   node scripts/journey-map-counts.mjs --check   exit 1 if MAP.md's table is stale or a row has no stage

